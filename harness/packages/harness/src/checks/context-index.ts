// expect:context-index-no-date
import { access, readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { parse, stringify } from 'yaml';
import type { Diagnostic } from '../diagnostics.ts';
import { DELTA_DIR } from './delta.ts';
import { normalizeEol, parseFrontmatter } from '../frontmatter.ts';

export const CONTEXT_INDEX_PATH = 'context/index.yml';
const PROJECT_PATH = 'context/project.yml';
const HEADER = '# generated by harness context index — do not edit manually\n';

const LAYERS = {
  entities: 'docs/entities',
  behaviors: 'docs/behavior',
  manuals: 'docs/manuals',
  conventions: 'context/conventions',
} as const;

interface NamespaceIndex {
  description?: string;
  entities: Map<string, string | null>;
  behaviors: Map<string, string | null>;
  manuals: Map<string, string | null>;
  /** Слои модулей: секция → id → заголовок. */
  layers: Map<string, Map<string, string | null>>;
}

/** Слой модуля из `provides.index_layers` его manifest'а. */
interface ModuleLayer {
  section: string;
  dir: string;
  /** `md` — frontmatter + `# …`; `yml` — YAML с `id`, `namespace`, `summary`. */
  format: 'md' | 'yml';
  manifest: string;
}

const MODULES_DIR = 'context/modules';
const RESERVED_SECTIONS = new Set(['description', 'entities', 'behaviors', 'manuals']);

/** Первый заголовок `# …` после frontmatter (комментарии YAML не считаются). */
function firstHeading(text: string): string | null {
  const lines = normalizeEol(text).split('\n');
  let start = 0;
  if (lines[0] === '---') {
    const end = lines.indexOf('---', 1);
    if (end !== -1) start = end + 1;
  }
  const h1 = lines.slice(start).find((line) => line.startsWith('# '));
  return h1 === undefined ? null : h1.slice(2).trim();
}

export interface ContextIndexResult {
  /** Готовый текст `context/index.yml`. */
  text: string;
  diagnostics: Diagnostic[];
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Файлы с расширением `ext` под `dir`, рекурсивно; пути от корня через `/`. */
async function listFiles(root: string, dir: string, ext: string): Promise<string[]> {
  let names: string[];
  try {
    names = await readdir(path.join(root, dir), { recursive: true });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
  return names
    .filter((name) => name.endsWith(ext))
    .map((name) => `${dir}/${name.split(path.sep).join('/')}`)
    .filter((file) => !file.startsWith(`${DELTA_DIR}/`))
    .sort();
}

const baseName = (file: string, ext: string): string => path.posix.basename(file, ext);

/** Имя manual из ссылки: `x`, `x.md` или `docs/manuals/x.md` → `x`. */
const manualName = (ref: string): string => path.posix.basename(ref, '.md');

class Collector {
  readonly diagnostics: Diagnostic[] = [];
  readonly namespaces = new Map<string, NamespaceIndex>();
  readonly conventions = new Map<string, string | null>();
  /** `null` — project.yml нет, namespace не проверяются. */
  declared: Set<string> | null = null;

  private readonly root: string;

  constructor(root: string) {
    this.root = root;
  }

  report(file: string, message: string): void {
    this.diagnostics.push({ file, message });
  }

  async readYaml(file: string): Promise<Record<string, unknown> | null> {
    let data: unknown;
    try {
      data = parse(await readFile(path.join(this.root, file), 'utf8'));
    } catch (error) {
      this.report(file, `невалидный YAML: ${(error as Error).message.split('\n')[0]}`);
      return null;
    }
    if (!isRecord(data)) {
      this.report(file, 'корень должен быть объектом');
      return null;
    }
    return data;
  }

  namespace(name: string): NamespaceIndex {
    let ns = this.namespaces.get(name);
    if (ns === undefined) {
      ns = { entities: new Map(), behaviors: new Map(), manuals: new Map(), layers: new Map() };
      this.namespaces.set(name, ns);
    }
    return ns;
  }

  /** Однострочный текст поля; нет или многострочный — нарушение и `null`. */
  oneLine(file: string, data: Record<string, unknown>, field: string): string | null {
    const value = data[field];
    if (typeof value !== 'string' || value.trim() === '') {
      this.report(file, `нет поля ${field} (одна строка для индекса)`);
      return null;
    }
    if (value.trim().includes('\n')) {
      this.report(file, `${field} должно быть одной строкой`);
      return null;
    }
    return value.trim();
  }

  checkId(
    file: string,
    data: Record<string, unknown>,
    field: 'id' | 'key',
    ext: string,
  ): string | null {
    const expected = baseName(file, ext);
    const id = data[field];
    if (typeof id !== 'string' || id === '') {
      this.report(file, `нет поля ${field}`);
      return null;
    }
    if (id !== expected)
      this.report(file, `${field} «${id}» не совпадает с именем файла «${expected}»`);
    return id;
  }

  checkNamespace(file: string, data: Record<string, unknown>): string | null {
    const ns = data['namespace'];
    if (typeof ns !== 'string' || ns === '') {
      this.report(file, 'нет поля namespace');
      return null;
    }
    if (this.declared !== null && !this.declared.has(ns)) {
      this.report(file, `namespace «${ns}» не объявлен в ${PROJECT_PATH} → namespaces`);
    }
    return ns;
  }

  async loadProject(): Promise<void> {
    try {
      await access(path.join(this.root, PROJECT_PATH));
    } catch {
      this.report(PROJECT_PATH, 'файл не найден: namespace не проверяются');
      return;
    }
    const data = await this.readYaml(PROJECT_PATH);
    if (data === null) return;
    const namespaces = data['namespaces'];
    if (!isRecord(namespaces)) {
      this.report(PROJECT_PATH, 'нет раздела namespaces');
      return;
    }
    this.declared = new Set(Object.keys(namespaces));
    for (const [name, description] of Object.entries(namespaces)) {
      const ns = this.namespace(name);
      if (typeof description === 'string' && description.trim() !== '')
        ns.description = description.trim();
    }
  }

  async collect(): Promise<void> {
    await this.loadProject();
    const manualRefs = new Map<string, Set<string>>();

    for (const file of await listFiles(this.root, LAYERS.entities, '.yml')) {
      const data = await this.readYaml(file);
      if (data === null) continue;
      const id = this.checkId(file, data, 'id', '.yml');
      const ns = this.checkNamespace(file, data);
      const summary = this.oneLine(file, data, 'summary');
      if (id === null || ns === null) continue;
      this.namespace(ns).entities.set(id, summary);
      const manuals = data['manuals'];
      if (Array.isArray(manuals)) {
        for (const ref of manuals) {
          if (typeof ref !== 'string') continue;
          const name = manualName(ref);
          manualRefs.set(name, (manualRefs.get(name) ?? new Set()).add(ns));
        }
      }
    }

    for (const file of await listFiles(this.root, LAYERS.behaviors, '.yml')) {
      const data = await this.readYaml(file);
      if (data === null) continue;
      const id = this.checkId(file, data, 'id', '.yml');
      const ns = this.checkNamespace(file, data);
      const title = this.oneLine(file, data, 'title');
      if (id === null || ns === null) continue;
      this.namespace(ns).behaviors.set(id, title);
    }

    for (const file of await listFiles(this.root, LAYERS.conventions, '.yml')) {
      const data = await this.readYaml(file);
      if (data === null) continue;
      const key = this.checkId(file, data, 'key', '.yml');
      const summary = this.oneLine(file, data, 'summary');
      if (key === null) continue;
      if (this.conventions.has(key)) this.report(file, `key «${key}» уже занят другой convention`);
      this.conventions.set(key, summary);
    }

    for (const file of await listFiles(this.root, LAYERS.manuals, '.md')) {
      const name = baseName(file, '.md');
      const title = firstHeading(await readFile(path.join(this.root, file), 'utf8'));
      if (title === null) this.report(file, 'нет заголовка «# …» (одна строка для индекса)');
      const owners = manualRefs.get(name);
      if (owners === undefined) {
        this.report(
          file,
          'manual не упомянут ни в одной entity (поле manuals) — namespace не определить',
        );
        continue;
      }
      for (const ns of owners) this.namespace(ns).manuals.set(name, title);
    }

    for (const layer of await this.loadModuleLayers()) await this.collectLayer(layer);
  }

  /** Слои, которые модули объявили в `provides.index_layers`. */
  async loadModuleLayers(): Promise<ModuleLayer[]> {
    const layers: ModuleLayer[] = [];
    for (const manifest of await listFiles(this.root, MODULES_DIR, '.yml')) {
      const data = await this.readYaml(manifest);
      if (data === null) continue;
      const provides = data['provides'];
      const declared = isRecord(provides) ? provides['index_layers'] : undefined;
      if (declared === undefined || declared === null) continue;
      if (!Array.isArray(declared)) {
        this.report(manifest, 'provides.index_layers должно быть списком');
        continue;
      }
      for (const item of declared) {
        const section = isRecord(item) ? item['section'] : undefined;
        const dir = isRecord(item) ? item['dir'] : undefined;
        if (
          typeof section !== 'string' ||
          !/^[a-z][a-z0-9-]*$/.test(section) ||
          RESERVED_SECTIONS.has(section)
        ) {
          this.report(
            manifest,
            `index_layers: section «${String(section)}» — нужен kebab-case, не ${[...RESERVED_SECTIONS].join('/')}`,
          );
          continue;
        }
        if (
          typeof dir !== 'string' ||
          dir === '' ||
          path.isAbsolute(dir) ||
          dir.split('/').includes('..')
        ) {
          this.report(manifest, `index_layers: dir «${String(dir)}» — нужен путь внутри проекта`);
          continue;
        }
        const format = (isRecord(item) ? item['format'] : undefined) ?? 'md';
        if (format !== 'md' && format !== 'yml') {
          this.report(
            manifest,
            `index_layers: format «${typeof format === 'string' ? format : JSON.stringify(format)}» — md или yml`,
          );
          continue;
        }
        const taken = layers.find((l) => l.section === section);
        if (taken !== undefined) {
          this.report(
            manifest,
            `index_layers: section «${section}» уже объявлена в ${taken.manifest}`,
          );
          continue;
        }
        layers.push({ section, dir: dir.replace(/\/+$/, ''), format, manifest });
      }
    }
    return layers;
  }

  /**
   * Файл слоя модуля: `md` — frontmatter `id`, `namespace`, строка индекса —
   * первый `# …`; `yml` — поля `id`, `namespace`, `summary`. `id` = путь
   * внутри слоя без расширения, `/` → `-`.
   */
  async collectLayer(layer: ModuleLayer): Promise<void> {
    const ext = layer.format === 'md' ? '.md' : '.yml';
    for (const file of await listFiles(this.root, layer.dir, ext)) {
      let data: Record<string, unknown> | null;
      let title: string | null;
      if (layer.format === 'yml') {
        data = await this.readYaml(file);
        if (data === null) continue;
        title = this.oneLine(file, data, 'summary');
      } else {
        const text = await readFile(path.join(this.root, file), 'utf8');
        try {
          data = parseFrontmatter(text);
        } catch (error) {
          this.report(file, `невалидный frontmatter: ${(error as Error).message.split('\n')[0]}`);
          continue;
        }
        if (data === null) {
          this.report(file, 'нет frontmatter (id, namespace)');
          continue;
        }
        title = firstHeading(text);
        if (title === null) this.report(file, 'нет заголовка «# …» (одна строка для индекса)');
      }
      const expected = file
        .slice(layer.dir.length + 1, -ext.length)
        .split('/')
        .join('-');
      const id = data['id'];
      if (typeof id !== 'string' || id === '') {
        this.report(file, 'нет поля id');
        continue;
      }
      if (id !== expected) this.report(file, `id «${id}» не совпадает с путём «${expected}»`);
      const ns = this.checkNamespace(file, data);
      if (ns === null) continue;
      const sections = this.namespace(ns).layers;
      const entries = sections.get(layer.section) ?? new Map<string, string | null>();
      if (entries.has(id)) this.report(file, `id «${id}» уже занят в слое ${layer.section}`);
      entries.set(id, title);
      sections.set(layer.section, entries);
    }
  }
}

const sorted = (map: Map<string, string | null>): Record<string, string | null> =>
  Object.fromEntries([...map.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));

function render(collector: Collector): string {
  const namespaces: Record<string, Record<string, unknown>> = {};
  // Порядок namespace — как в project.yml; необъявленные — следом по алфавиту.
  const declared = [...collector.namespaces.keys()].filter((n) => collector.declared?.has(n));
  const extra = [...collector.namespaces.keys()].filter((n) => !collector.declared?.has(n)).sort();
  for (const name of [...declared, ...extra]) {
    const ns = collector.namespaces.get(name);
    if (ns === undefined) continue;
    const out: Record<string, unknown> = {};
    if (ns.description !== undefined) out['description'] = ns.description;
    for (const section of ['entities', 'behaviors', 'manuals'] as const) {
      if (ns[section].size > 0) out[section] = sorted(ns[section]);
    }
    for (const section of [...ns.layers.keys()].sort()) {
      const entries = ns.layers.get(section);
      if (entries !== undefined && entries.size > 0) out[section] = sorted(entries);
    }
    namespaces[name] = out;
  }
  const doc: Record<string, unknown> = {};
  if (collector.conventions.size > 0) doc['conventions'] = sorted(collector.conventions);
  if (Object.keys(namespaces).length > 0) doc['namespaces'] = namespaces;
  return HEADER + stringify(doc, { lineWidth: 0 });
}

/** Собирает `context/index.yml` из слоёв документации. */
export async function buildContextIndex(root: string): Promise<ContextIndexResult> {
  const collector = new Collector(root);
  await collector.collect();
  return { text: render(collector), diagnostics: collector.diagnostics };
}

/** Проверка для `harness check`: нарушения слоёв + индекс совпадает с собранным. */
export async function checkContextIndex(root: string): Promise<Diagnostic[]> {
  const { text, diagnostics } = await buildContextIndex(root);
  let actual: string | null = null;
  try {
    actual = await readFile(path.join(root, CONTEXT_INDEX_PATH), 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  if (actual === null) {
    diagnostics.push({
      file: CONTEXT_INDEX_PATH,
      message: 'файл не найден: запусти harness context index',
    });
  } else if (normalizeEol(actual) !== text) {
    diagnostics.push({
      file: CONTEXT_INDEX_PATH,
      message: 'устарел: запусти harness context index',
    });
  }
  return diagnostics;
}
