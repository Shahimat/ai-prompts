import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { parse, stringify } from 'yaml';
import { normalizeEol, parseFrontmatter } from './frontmatter.ts';

export const INDEX_PATH = 'prompts/index.yml';
const SOURCE_DIRS = ['prompts', 'patterns'] as const;
const HEADER = '# generated by harness index build — do not edit manually';

const SKILLS_DIR = 'skills';
const AGENTS_DIR = 'agents';
const PRESETS_DIR = 'presets';

const GROUPS = [
  { kind: 'contract', label: 'contracts' },
  { kind: 'pattern', label: 'patterns' },
  { kind: 'module', label: 'modules' },
  { kind: 'skill', label: 'skills' },
  { kind: 'agent', label: 'agents' },
  { kind: 'preset', label: 'presets' },
  { kind: 'prompt', label: 'prompts' },
] as const;

export interface IndexEntry {
  kind: string;
  key: string;
  /** Путь от корня репозитория, всегда через `/`. */
  path: string;
  sha256: string;
  applicableTo: string[];
  patterns: string[];
  title?: string;
  /** Блок `feature` модуля-возможности — то, что нужно для чеклиста. */
  feature?: FeatureInfo;
  /** Файлы skill: `path` от корня репозитория и SHA-256 каждого. */
  files?: { path: string; sha256: string }[];
}

export interface FeatureInfo {
  summary: string;
  default: boolean;
  requires: string[];
  conflicts: string[];
}

/** Поля `feature` во frontmatter; `asks` читается из самого модуля, в индекс не идёт. */
const FEATURE_KEYS = ['summary', 'default', 'requires', 'conflicts', 'asks'];

export interface CollectResult {
  entries: IndexEntry[];
  /** Файлы без `key` / `kind` во frontmatter (README и т.п.). */
  skipped: string[];
}

/** SHA-256 от содержимого с LF, чтобы хэш совпадал на любой ОС. */
export function sha256(content: string): string {
  return createHash('sha256').update(normalizeEol(content), 'utf8').digest('hex');
}

function stringList(value: unknown, field: string, file: string): string[] {
  if (value === undefined || value === null) return [];
  if (!Array.isArray(value) || !value.every((v): v is string => typeof v === 'string')) {
    throw new Error(`${file}: поле ${field} должно быть списком строк`);
  }
  return value;
}

function oneLine(value: unknown, field: string, file: string): string | undefined {
  if (value === undefined || value === null) return undefined;
  if (typeof value !== 'string' || value.trim() === '' || value.trim().includes('\n')) {
    throw new Error(`${file}: поле ${field} должно быть непустой строкой в одну строку`);
  }
  return value.trim();
}

function parseFeature(value: unknown, kind: string, file: string): FeatureInfo | undefined {
  if (value === undefined || value === null) return undefined;
  if (kind !== 'module') throw new Error(`${file}: feature допустим только у kind: module`);
  if (typeof value !== 'object' || Array.isArray(value)) throw new Error(`${file}: feature должно быть объектом`);
  const feature = value as Record<string, unknown>;
  const extra = Object.keys(feature).filter((k) => !FEATURE_KEYS.includes(k));
  if (extra.length > 0) throw new Error(`${file}: неизвестные поля feature: ${extra.join(', ')}`);
  const summary = oneLine(feature['summary'], 'feature.summary', file);
  if (summary === undefined) throw new Error(`${file}: нет feature.summary`);
  if (typeof feature['default'] !== 'boolean') throw new Error(`${file}: feature.default должно быть true или false`);
  return {
    summary,
    default: feature['default'],
    requires: stringList(feature['requires'], 'feature.requires', file),
    conflicts: stringList(feature['conflicts'], 'feature.conflicts', file),
  };
}

/** requires / conflicts ссылаются только на модули из индекса и не на себя. */
function checkFeatureRefs(entries: IndexEntry[]): void {
  const modules = new Set(entries.filter((e) => e.kind === 'module').map((e) => e.key));
  for (const e of entries) {
    if (e.feature === undefined) continue;
    for (const field of ['requires', 'conflicts'] as const) {
      for (const ref of e.feature[field]) {
        if (ref === e.key) throw new Error(`${e.path}: feature.${field} ссылается на сам модуль`);
        if (!modules.has(ref)) throw new Error(`${e.path}: feature.${field}: модуля «${ref}» нет в индексе`);
      }
    }
  }
}

function compareBytes(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

async function listMarkdown(root: string): Promise<string[]> {
  const files: string[] = [];
  for (const dir of SOURCE_DIRS) {
    let names: string[];
    try {
      names = await readdir(path.join(root, dir), { recursive: true });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') continue;
      throw error;
    }
    for (const name of names) {
      if (name.endsWith('.md')) files.push(`${dir}/${name.split(path.sep).join('/')}`);
    }
  }
  return files.sort(compareBytes);
}

export async function collectEntries(root: string): Promise<CollectResult> {
  const entries: IndexEntry[] = [];
  const skipped: string[] = [];
  for (const file of await listMarkdown(root)) {
    const content = await readFile(path.join(root, file), 'utf8');
    let fm;
    try {
      fm = parseFrontmatter(content);
    } catch (error) {
      throw new Error(`${file}: ${(error as Error).message}`, { cause: error });
    }
    const key = fm?.['key'];
    const kind = fm?.['kind'];
    if (typeof key !== 'string' || key === '' || typeof kind !== 'string' || kind === '') {
      skipped.push(file);
      continue;
    }
    const entry: IndexEntry = {
      kind,
      key,
      path: file,
      sha256: sha256(content),
      applicableTo: stringList(fm?.['applicable_to'], 'applicable_to', file),
      patterns: stringList(fm?.['patterns'], 'patterns', file),
    };
    const title = oneLine(fm?.['title'], 'title', file);
    if (title !== undefined) entry.title = title;
    const feature = parseFeature(fm?.['feature'], kind, file);
    if (feature !== undefined) entry.feature = feature;
    entries.push(entry);
  }
  entries.push(...(await collectSkills(root)), ...(await collectAgents(root)));
  checkFeatureRefs(entries);
  entries.push(...(await collectPresets(root, entries)));
  return { entries, skipped };
}

async function listNames(abs: string): Promise<string[]> {
  try {
    return (await readdir(abs)).sort(compareBytes);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
}

/** name во frontmatter совпадает с именем; description — однострочный title записи. */
function nameAndTitle(content: string, expected: string, file: string): string {
  let fm;
  try {
    fm = parseFrontmatter(content);
  } catch (error) {
    throw new Error(`${file}: ${(error as Error).message}`, { cause: error });
  }
  if (fm?.['name'] !== expected) throw new Error(`${file}: name должно совпадать с именем «${expected}»`);
  const title = oneLine(fm['description'], 'description', file);
  if (title === undefined) throw new Error(`${file}: нет description`);
  return title;
}

/**
 * Skill — каталог `skills/<name>/` с `SKILL.md` по стандарту Agent Skills.
 * SHA-256 skill — от строк `<sha256 файла>  <путь внутри skill>`, по одной
 * на файл, в порядке путей: меняется при правке любого файла.
 */
async function collectSkills(root: string): Promise<IndexEntry[]> {
  const entries: IndexEntry[] = [];
  for (const name of await listNames(path.join(root, SKILLS_DIR))) {
    const dir = `${SKILLS_DIR}/${name}`;
    const rels = (await readdir(path.join(root, dir), { recursive: true, withFileTypes: true }))
      .filter((e) => e.isFile())
      .map((e) => path.relative(path.join(root, dir), path.join(e.parentPath, e.name)).split(path.sep).join('/'))
      .sort(compareBytes);
    if (!rels.includes('SKILL.md')) throw new Error(`${dir}: нет SKILL.md`);
    const files: { path: string; sha256: string }[] = [];
    let title = '';
    for (const rel of rels) {
      const content = await readFile(path.join(root, dir, rel), 'utf8');
      if (rel === 'SKILL.md') title = nameAndTitle(content, name, `${dir}/SKILL.md`);
      files.push({ path: `${dir}/${rel}`, sha256: sha256(content) });
    }
    const manifest = files.map((f, i) => `${f.sha256}  ${rels[i] ?? ''}\n`).join('');
    entries.push({ kind: 'skill', key: name, path: dir, sha256: sha256(manifest), applicableTo: [], patterns: [], title, files });
  }
  return entries;
}

/**
 * Пресет — `presets/<key>.yml`: готовый набор возможностей для типа
 * проекта. Модули пресета должны быть в индексе и применимы к его контракту.
 */
async function collectPresets(root: string, known: IndexEntry[]): Promise<IndexEntry[]> {
  const entries: IndexEntry[] = [];
  for (const entry of await listNames(path.join(root, PRESETS_DIR))) {
    if (!entry.endsWith('.yml')) continue;
    const file = `${PRESETS_DIR}/${entry}`;
    const key = entry.slice(0, -4);
    const content = await readFile(path.join(root, file), 'utf8');
    let data: unknown;
    try {
      data = parse(content);
    } catch (error) {
      throw new Error(`${file}: невалидный YAML: ${(error as Error).message.split('\n')[0]}`, { cause: error });
    }
    if (typeof data !== 'object' || data === null || Array.isArray(data)) throw new Error(`${file}: корень должен быть объектом`);
    const preset = data as Record<string, unknown>;
    if (preset['key'] !== key) throw new Error(`${file}: key должно совпадать с именем файла «${key}»`);
    const title = oneLine(preset['title'], 'title', file);
    if (title === undefined) throw new Error(`${file}: нет title`);
    const contract = preset['contract'];
    if (!known.some((e) => e.kind === 'contract' && e.key === contract)) {
      throw new Error(`${file}: контракта «${String(contract)}» нет в индексе`);
    }
    const modules = preset['modules'];
    if (!Array.isArray(modules) || modules.length === 0) throw new Error(`${file}: modules — непустой список`);
    for (const item of modules) {
      const moduleKey = typeof item === 'object' && item !== null ? (item as Record<string, unknown>)['key'] : undefined;
      const module = known.find((e) => e.kind === 'module' && e.key === moduleKey);
      if (module === undefined) throw new Error(`${file}: модуля «${String(moduleKey)}» нет в индексе`);
      if (!module.applicableTo.includes(String(contract))) {
        throw new Error(`${file}: модуль «${module.key}» не применим к «${String(contract)}»`);
      }
    }
    entries.push({ kind: 'preset', key, path: file, sha256: sha256(content), applicableTo: [String(contract)], patterns: [], title });
  }
  return entries;
}

/** Субагент — `agents/<name>.md`: frontmatter name, description, skills, tools + инструкция. */
async function collectAgents(root: string): Promise<IndexEntry[]> {
  const entries: IndexEntry[] = [];
  for (const entry of await listNames(path.join(root, AGENTS_DIR))) {
    if (!entry.endsWith('.md')) continue;
    const file = `${AGENTS_DIR}/${entry}`;
    const content = await readFile(path.join(root, file), 'utf8');
    const title = nameAndTitle(content, entry.slice(0, -3), file);
    entries.push({ kind: 'agent', key: entry.slice(0, -3), path: file, sha256: sha256(content), applicableTo: [], patterns: [], title });
  }
  return entries;
}

export interface RenderOptions {
  /** Префикс raw-URL без завершающего `/`. */
  rawBase: string;
  generatedAt: Date;
}

const flowList = (items: string[]): string => `[${items.join(', ')}]`;
/** Скаляр через YAML-сериализатор: кавычки появятся, только если без них YAML сломается. */
const scalar = (value: string | boolean): string => stringify(value, { lineWidth: 0 }).trimEnd();

export function renderIndex(entries: IndexEntry[], options: RenderOptions): string {
  const timestamp = options.generatedAt.toISOString().replace(/\.\d{3}Z$/, 'Z');
  const lines = [HEADER, `generated_at: ${timestamp}`];
  for (const group of GROUPS) {
    const items = entries.filter((e) => e.kind === group.kind);
    lines.push('');
    if (items.length === 0) {
      lines.push(`${group.label}: []`);
      continue;
    }
    lines.push(`${group.label}:`);
    for (const e of items) {
      lines.push(
        `  - key: ${e.key}`,
        ...(e.title === undefined ? [] : [`    title: ${scalar(e.title)}`]),
        `    path: ${e.path}`,
        // У skill raw нет: это каталог, raw — у каждого файла.
        ...(e.files === undefined ? [`    raw: ${options.rawBase}/${e.path}`] : []),
        `    sha256: ${e.sha256}`,
      );
      if (e.files !== undefined) {
        lines.push('    files:');
        for (const f of e.files) {
          lines.push(`      - path: ${f.path}`, `        raw: ${options.rawBase}/${f.path}`, `        sha256: ${f.sha256}`);
        }
      }
      if (e.patterns.length > 0) lines.push(`    patterns: ${flowList(e.patterns)}`);
      if ((e.kind === 'module' || e.kind === 'preset') && e.applicableTo.length > 0) {
        lines.push(`    applicable_to: ${flowList(e.applicableTo)}`);
      }
      if (e.feature !== undefined) {
        lines.push(
          '    feature:',
          `      summary: ${scalar(e.feature.summary)}`,
          `      default: ${scalar(e.feature.default)}`,
          `      requires: ${flowList(e.feature.requires)}`,
          `      conflicts: ${flowList(e.feature.conflicts)}`,
        );
      }
    }
  }
  return `${lines.join('\n')}\n`;
}

/** Убирает строку `generated_at`: она меняется на каждой сборке. */
export function stripTimestamp(index: string): string {
  return normalizeEol(index)
    .split('\n')
    .filter((line) => !line.startsWith('generated_at:'))
    .join('\n');
}

export interface IndexDiff {
  line: number;
  expected: string | undefined;
  actual: string | undefined;
}

/** Построчное сравнение без учёта `generated_at`; пустой массив — индексы совпадают. */
export function diffIndex(expected: string, actual: string): IndexDiff[] {
  const exp = stripTimestamp(expected).split('\n');
  const act = stripTimestamp(actual).split('\n');
  const diffs: IndexDiff[] = [];
  for (let i = 0; i < Math.max(exp.length, act.length); i++) {
    if (exp[i] !== act[i]) diffs.push({ line: i + 1, expected: exp[i], actual: act[i] });
  }
  return diffs;
}
