import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { normalizeEol, parseFrontmatter } from './frontmatter.ts';

export const INDEX_PATH = 'prompts/index.yml';
const SOURCE_DIRS = ['prompts', 'patterns'] as const;
const HEADER = '# generated by scripts/build-index.sh — do not edit manually';

const GROUPS = [
  { kind: 'contract', label: 'contracts' },
  { kind: 'pattern', label: 'patterns' },
  { kind: 'module', label: 'modules' },
  { kind: 'prompt', label: 'prompts' },
] as const;

export interface IndexEntry {
  kind: string;
  key: string;
  /** Путь от корня репозитория, всегда через `/`. */
  path: string;
  sha256: string;
  applicableTo: string[];
  patterns: string[];
}

export interface CollectResult {
  entries: IndexEntry[];
  /** Файлы без `key` / `kind` во frontmatter (README и т.п.). */
  skipped: string[];
}

/** SHA-256 от содержимого с LF, чтобы хэш совпадал на любой ОС. */
export function sha256(content: string): string {
  return createHash('sha256').update(normalizeEol(content), 'utf8').digest('hex');
}

function stringList(value: unknown, field: string, file: string): string[] {
  if (value === undefined || value === null) return [];
  if (!Array.isArray(value) || !value.every((v): v is string => typeof v === 'string')) {
    throw new Error(`${file}: поле ${field} должно быть списком строк`);
  }
  return value;
}

function compareBytes(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

async function listMarkdown(root: string): Promise<string[]> {
  const files: string[] = [];
  for (const dir of SOURCE_DIRS) {
    let names: string[];
    try {
      names = await readdir(path.join(root, dir), { recursive: true });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') continue;
      throw error;
    }
    for (const name of names) {
      if (name.endsWith('.md')) files.push(`${dir}/${name.split(path.sep).join('/')}`);
    }
  }
  return files.sort(compareBytes);
}

export async function collectEntries(root: string): Promise<CollectResult> {
  const entries: IndexEntry[] = [];
  const skipped: string[] = [];
  for (const file of await listMarkdown(root)) {
    const content = await readFile(path.join(root, file), 'utf8');
    let fm;
    try {
      fm = parseFrontmatter(content);
    } catch (error) {
      throw new Error(`${file}: ${(error as Error).message}`, { cause: error });
    }
    const key = fm?.['key'];
    const kind = fm?.['kind'];
    if (typeof key !== 'string' || key === '' || typeof kind !== 'string' || kind === '') {
      skipped.push(file);
      continue;
    }
    entries.push({
      kind,
      key,
      path: file,
      sha256: sha256(content),
      applicableTo: stringList(fm?.['applicable_to'], 'applicable_to', file),
      patterns: stringList(fm?.['patterns'], 'patterns', file),
    });
  }
  return { entries, skipped };
}

export interface RenderOptions {
  /** Префикс raw-URL без завершающего `/`. */
  rawBase: string;
  generatedAt: Date;
}

const flowList = (items: string[]): string => `[${items.join(', ')}]`;

export function renderIndex(entries: IndexEntry[], options: RenderOptions): string {
  const timestamp = options.generatedAt.toISOString().replace(/\.\d{3}Z$/, 'Z');
  const lines = [HEADER, `generated_at: ${timestamp}`];
  for (const group of GROUPS) {
    const items = entries.filter((e) => e.kind === group.kind);
    lines.push('');
    if (items.length === 0) {
      lines.push(`${group.label}: []`);
      continue;
    }
    lines.push(`${group.label}:`);
    for (const e of items) {
      lines.push(
        `  - key: ${e.key}`,
        `    path: ${e.path}`,
        `    raw: ${options.rawBase}/${e.path}`,
        `    sha256: ${e.sha256}`,
      );
      if (e.patterns.length > 0) lines.push(`    patterns: ${flowList(e.patterns)}`);
      if (e.kind === 'module' && e.applicableTo.length > 0) {
        lines.push(`    applicable_to: ${flowList(e.applicableTo)}`);
      }
    }
  }
  return `${lines.join('\n')}\n`;
}

/** Убирает строку `generated_at`: она меняется на каждой сборке. */
export function stripTimestamp(index: string): string {
  return normalizeEol(index)
    .split('\n')
    .filter((line) => !line.startsWith('generated_at:'))
    .join('\n');
}

export interface IndexDiff {
  line: number;
  expected: string | undefined;
  actual: string | undefined;
}

/** Построчное сравнение без учёта `generated_at`; пустой массив — индексы совпадают. */
export function diffIndex(expected: string, actual: string): IndexDiff[] {
  const exp = stripTimestamp(expected).split('\n');
  const act = stripTimestamp(actual).split('\n');
  const diffs: IndexDiff[] = [];
  for (let i = 0; i < Math.max(exp.length, act.length); i++) {
    if (exp[i] !== act[i]) diffs.push({ line: i + 1, expected: exp[i], actual: act[i] });
  }
  return diffs;
}
