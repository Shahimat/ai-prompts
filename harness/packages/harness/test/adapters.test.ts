import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { parse as parseYaml } from 'yaml';
import { codexAgent } from '../src/commands/adapters/render.ts';
import { readSources, type AgentDef } from '../src/commands/adapters/source.ts';
import { applyActions, checkAdapters, computeSync } from '../src/commands/adapters/sync.ts';
import type { AdapterName } from '../src/shared/config.ts';
import { parseFrontmatter } from '../src/shared/frontmatter.ts';

const BOTH: AdapterName[] = ['claude-code', 'codex'];
let root: string;

async function put(rel: string, content: string | Buffer): Promise<void> {
  await mkdir(path.dirname(path.join(root, rel)), { recursive: true });
  await writeFile(path.join(root, rel), content);
}

const read = (rel: string): Promise<string> => readFile(path.join(root, rel), 'utf8');
const exists = (rel: string): Promise<boolean> =>
  stat(path.join(root, rel)).then(
    () => true,
    () => false,
  );

async function sync(adapters: AdapterName[] = BOTH): Promise<string[]> {
  const { actions, diagnostics } = await computeSync(root, adapters);
  await applyActions(root, actions);
  return diagnostics.map((d) => `${d.file}: ${d.message}`);
}

async function seed(): Promise<void> {
  await put('AGENTS.md', '# Проект\n');
  await put(
    '.agents/skills/docs-keeper/SKILL.md',
    '---\nname: docs-keeper\ndescription: ведёт доку\n---\nтело\n',
  );
  await put('.agents/skills/docs-keeper/scripts/run.js', 'console.log(1)\n');
  await put('.agents/skills/docs-keeper/assets/logo.bin', Buffer.from([0, 255, 1, 2]));
  await put(
    '.agents/agents/docs-keeper.md',
    '---\nname: docs-keeper\ndescription: "Раскладывает факты: по слоям"\nskills: [docs-keeper]\ntools: [Read, Edit]\n---\n\nИнструкция.\n',
  );
}

beforeEach(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'harness-adapters-'));
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

describe('adapters sync', () => {
  it('генерирует файлы claude-code и codex', async () => {
    await seed();
    expect(await sync()).toEqual([]);

    expect(await read('CLAUDE.md')).toMatch(
      /^<!-- generated by harness adapters sync .*-->\n@AGENTS\.md\n$/,
    );
    expect(await read('.claude/skills/docs-keeper/SKILL.md')).toBe(
      await read('.agents/skills/docs-keeper/SKILL.md'),
    );
    expect(await read('.claude/skills/docs-keeper/scripts/run.js')).toBe('console.log(1)\n');
    expect([
      ...(await readFile(path.join(root, '.claude/skills/docs-keeper/assets/logo.bin'))),
    ]).toEqual([0, 255, 1, 2]);
    expect(await exists('.claude/skills/docs-keeper/.harness-generated')).toBe(true);

    const claudeAgent = await read('.claude/agents/docs-keeper.md');
    expect(parseFrontmatter(claudeAgent)).toEqual({
      name: 'docs-keeper',
      description: 'Раскладывает факты: по слоям',
      tools: 'Read, Edit',
      skills: ['docs-keeper'],
    });
    expect(claudeAgent.endsWith('---\n\nИнструкция.\n')).toBe(true);

    const toml = await read('.codex/agents/docs-keeper.toml');
    expect(toml).toContain('name = "docs-keeper"');
    expect(toml).toContain('description = "Раскладывает факты: по слоям"');
    expect(toml).toContain('Перед работой загрузи skills: docs-keeper.\n\nИнструкция.');
  });

  it('повторный sync ничего не меняет, check чист', async () => {
    await seed();
    await sync();
    expect((await computeSync(root, BOTH)).actions).toEqual([]);
    expect(await checkAdapters(root, BOTH)).toEqual([]);
  });

  it('только выбранные адаптеры', async () => {
    await seed();
    await sync(['codex']);
    expect(await exists('CLAUDE.md')).toBe(false);
    expect(await exists('.claude')).toBe(false);
    expect(await exists('.codex/agents/docs-keeper.toml')).toBe(true);
  });

  it('убирает сгенерированное, когда адаптер выключен или источник удалён', async () => {
    await seed();
    await sync();
    await rm(path.join(root, '.agents/skills/docs-keeper/scripts'), { recursive: true });
    await sync();
    expect(await exists('.claude/skills/docs-keeper/scripts/run.js')).toBe(false);

    await sync(['codex']);
    expect(await exists('CLAUDE.md')).toBe(false);
    expect(await exists('.claude/skills/docs-keeper')).toBe(false);
    expect(await exists('.claude/agents/docs-keeper.md')).toBe(false);

    await rm(path.join(root, '.agents/agents/docs-keeper.md'));
    await sync(['codex']);
    expect(await exists('.codex/agents/docs-keeper.toml')).toBe(false);
  });

  it('не трогает файлы, написанные вручную', async () => {
    await seed();
    await put('CLAUDE.md', '# мой CLAUDE.md\n');
    await put('.claude/skills/docs-keeper/SKILL.md', 'свой skill\n');
    await put('.claude/skills/mine/SKILL.md', 'чужой skill\n');
    await put('.claude/agents/mine.md', '---\nname: mine\n---\nсвой\n');

    expect(await sync()).toEqual([
      expect.stringMatching(/^CLAUDE\.md: существует и написан не harness/),
      expect.stringMatching(/^\.claude\/skills\/docs-keeper: существует и написан не harness/),
    ]);
    expect(await read('CLAUDE.md')).toBe('# мой CLAUDE.md\n');
    expect(await read('.claude/skills/docs-keeper/SKILL.md')).toBe('свой skill\n');
    expect(await read('.claude/skills/mine/SKILL.md')).toBe('чужой skill\n');
    expect(await read('.claude/agents/mine.md')).toBe('---\nname: mine\n---\nсвой\n');
    expect(await exists('.claude/agents/docs-keeper.md')).toBe(true);
  });

  it('check ловит ручную правку копии и забытый sync', async () => {
    await seed();
    await sync();
    await put('.claude/skills/docs-keeper/SKILL.md', 'поправил копию\n');
    await put('.agents/skills/docs-keeper/NEW.md', 'новый файл\n');
    expect((await checkAdapters(root, BOTH)).map((d) => `${d.file}: ${d.message}`)).toEqual([
      '.claude/skills/docs-keeper/NEW.md: отсутствует или устарел: запусти harness adapters sync',
      '.claude/skills/docs-keeper/SKILL.md: отсутствует или устарел: запусти harness adapters sync',
    ]);
  });

  it('без AGENTS.md CLAUDE.md не создаётся', async () => {
    expect(await sync(['claude-code'])).toEqual([
      'AGENTS.md: файл не найден: CLAUDE.md не из чего генерировать',
    ]);
  });
});

describe('readSources', () => {
  it('нарушения в описаниях субагентов и skills', async () => {
    await put('.agents/skills/no-skill-md/README.md', 'x');
    await put('.agents/agents/wrong.md', '---\nname: other\ndescription: d\n---\nтело\n');
    await put('.agents/agents/no-desc.md', '---\nname: no-desc\n---\nтело\n');
    await put('.agents/agents/empty.md', '---\nname: empty\ndescription: d\n---\n\n');
    await put(
      '.agents/agents/extra.md',
      '---\nname: extra\ndescription: d\nmodel: opus\nskills: [missing]\n---\nтело\n',
    );
    await put(
      '.agents/agents/bad-list.md',
      '---\nname: bad-list\ndescription: d\ntools: Read\n---\nтело\n',
    );
    await put('.agents/agents/no-fm.md', 'просто текст\n');

    const { agents, diagnostics } = await readSources(root);
    expect(agents.map((a) => a.name)).toEqual(['extra']);
    expect(diagnostics.map((d) => `${d.file}: ${d.message}`)).toEqual([
      '.agents/skills/no-skill-md: нет SKILL.md — не skill, пропущен',
      '.agents/agents/bad-list.md: tools должно быть списком строк',
      '.agents/agents/empty.md: пустое тело: инструкции субагента',
      '.agents/agents/extra.md: неизвестные поля frontmatter: model',
      '.agents/agents/extra.md: skill «missing» не найден в .agents/skills',
      '.agents/agents/no-desc.md: нет поля description',
      '.agents/agents/no-fm.md: нет frontmatter (--- name, description ---)',
      '.agents/agents/wrong.md: name «other» не совпадает с именем файла «wrong»',
    ]);
  });
});

describe('codexAgent', () => {
  const agent = (instructions: string): AgentDef => ({
    name: 'a',
    source: '.agents/agents/a.md',
    description: 'd "quoted"',
    skills: [],
    tools: [],
    instructions,
  });

  it('экранирует кавычки, обратные слэши и тройные кавычки', () => {
    const toml = codexAgent(agent('путь C:\\tmp, строка """ внутри и \u0001'));
    expect(toml).toContain('description = "d \\"quoted\\""');
    expect(toml).toContain('путь C:\\\\tmp, строка ""\\" внутри и \\u0001');
    expect(toml).not.toContain('Перед работой');
  });

  it('frontmatter claude-агента — валидный YAML с меткой-комментарием', async () => {
    await seed();
    await sync(['claude-code']);
    const fm = (await read('.claude/agents/docs-keeper.md')).split('---\n')[1] ?? '';
    expect(fm.split('\n')[0]).toMatch(/^# generated by harness adapters sync/);
    expect(parseYaml(fm)).toMatchObject({ name: 'docs-keeper' });
  });
});

describe('adapters sync: memory выключена', () => {
  it('claude-code: создаёт .claude/settings.json с autoMemoryEnabled: false', async () => {
    await put('AGENTS.md', '# x\n');
    expect(await sync(['claude-code'])).toEqual([]);
    expect(JSON.parse(await read('.claude/settings.json'))).toEqual({ autoMemoryEnabled: false });
    expect((await computeSync(root, ['claude-code'])).actions).toEqual([]);
  });

  it('claude-code: дописывает ключ, сохраняя permissions и прочее', async () => {
    await put('AGENTS.md', '# x\n');
    await put(
      '.claude/settings.json',
      '{"permissions":{"allow":["Bash(git status)"]},"autoMemoryEnabled":true}',
    );
    await sync(['claude-code']);
    expect(JSON.parse(await read('.claude/settings.json'))).toEqual({
      permissions: { allow: ['Bash(git status)'] },
      autoMemoryEnabled: false,
    });
  });

  it('claude-code: невалидный JSON не трогает', async () => {
    await put('AGENTS.md', '# x\n');
    await put('.claude/settings.json', '{ сломано');
    expect(await sync(['claude-code'])).toEqual([
      expect.stringMatching(/^\.claude\/settings\.json: невалидный JSON/),
    ]);
    expect(await read('.claude/settings.json')).toBe('{ сломано');
  });

  it('codex: создаёт .codex/config.toml, при выключении адаптера удаляет', async () => {
    expect(await sync(['codex'])).toEqual([]);
    const toml = await read('.codex/config.toml');
    expect(toml).toContain('[features]\nmemories = false');
    expect(toml).toContain('[memories]\nuse_memories = false\ngenerate_memories = false');
    expect(await checkAdapters(root, ['codex'])).toEqual([]);
    await sync(['claude-code']);
    expect(await exists('.codex/config.toml')).toBe(false);
  });

  it('codex: ручной config.toml не трогает, проверяет ключи', async () => {
    const manual =
      'model = "x"\n\n[features]\nmemories = false # выкл\n\n[memories]\nuse_memories = false\n';
    await put('.codex/config.toml', manual);
    expect(await sync(['codex'])).toEqual([
      '.codex/config.toml: написан вручную, memory не выключена: добавь memories.generate_memories = false',
    ]);
    expect(await read('.codex/config.toml')).toBe(manual);

    await put(
      '.codex/config.toml',
      'features.memories = false\nmemories.use_memories = false\nmemories.generate_memories = false\n',
    );
    expect(await sync(['codex'])).toEqual([]);
  });
});
