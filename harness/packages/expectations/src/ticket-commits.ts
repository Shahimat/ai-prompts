import { describe } from 'vitest';
import { crit, judged, warn } from '@shahimat/harness/expect';

/**
 * Ожидания к правилам «тикет и коммиты». `keys` — ключи якорей
 * `expect:KEY`, которыми в реализации проекта размечены эти правила:
 * переименование разделов и перенос текста ожидания не трогают.
 * Каждое ожидание проверяет судья по всем размеченным областям.
 */
export function ticketCommits(...keys: string[]): void {
  if (keys.length === 0) throw new Error('ticketCommits: нужен хотя бы один ключ якоря');
  const check = (): Promise<void> => judged(keys.map((k) => `@${k}`));

  describe('тикет — задача, техзадача или бага: последовательность шагов-коммитов', () => {
    crit('шаг тикета — один тип karma (feat, fix, refactor, docs, test, perf, chore, style) и один коммит; исключение — режим «пройти тикет целиком»', check);
    crit('подряд идущая работа одного типа — один коммит: если последний коммит того же типа, в сообщении коммита агент указывает git commit --amend', check);
    warn('в плане тикета соседние шаги одного типа объединены; scope и тема шаг не делят', check);
    warn('тип шага может повторяться после шага другого типа: feat → refactor → feat — три коммита', check);
    warn('вклинившийся refactor доводится до конца отдельным шагом, затем работа возвращается к прерванному типу', check);
    crit('генерируемые файлы (индексы, кэш вердиктов) — в коммит той правки, которая их изменила', check);
    warn('после шага агент останавливается с отчётом и сообщением коммита; не останавливается, если просили пройти тикет целиком', check);
    warn('при просьбе пройти целиком весь тикет — один коммит без дробления', check);
    warn('тип общего коммита — по виду тикета: бага → fix, задача → feat, техзадача → refactor или chore', check);
    crit('сообщение коммита — type(scope): subject; по умолчанию коммит делает пользователь', check);
    crit('git-запись (commit, amend, push) агент сам не выполняет; вне сообщения коммита в конце шага её не предлагает; выполняет только по явной просьбе после списка команд', check);
  });
}
