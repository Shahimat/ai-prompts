import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { isRecord } from '@shahimat/ai-core';
import { detectOldLayout, migrateLayout } from '#migrate';

let root: string;

beforeEach(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'oc3-migrate-'));
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

const put = async (rel: string, text: string): Promise<void> => {
  const abs = path.join(root, rel);
  await mkdir(path.dirname(abs), { recursive: true });
  await writeFile(abs, text, 'utf8');
};

const read = async (rel: string): Promise<string> => readFile(path.join(root, rel), 'utf8');

describe('detectOldLayout', () => {
  it('свежая раскладка — не старая', async () => {
    await put('.oc3/project.yml', 'name: x\n');
    expect(detectOldLayout(root)).toBe(false);
  });

  it('контрактовые подписи старой раскладки детектятся', async () => {
    await put('context/ai-core.yml', 'checks: {}\n');
    expect(detectOldLayout(root)).toBe(true);
  });

  it('goals без контракта — не повод для миграции', async () => {
    await put('goals/plan.md', '# план\n');
    expect(detectOldLayout(root)).toBe(false);
  });
});

describe('migrateLayout', () => {
  it('переносит context/, docs/, goals/, .ops/ по карте байт-в-байт и удаляет старые каталоги', async () => {
    const project = 'name: demo\nsync:\n  contract:\n    key: agent-operational-contract-v3\n';
    const convention = 'key: naming\nsummary: kebab-case\nrule: x\n';
    await put('context/project.yml', project);
    await put('context/ai-core.yml', 'checks:\n  changelog: {}\n');
    await put('context/skills.yml', 'skills: []\n');
    await put('context/autonomy.yml', 'levels:\n  never: [vcs.write]\n');
    await put('context/index.yml', '# generated by ai context index\n');
    await put('context/conventions/naming.yml', convention);
    await put('context/.delta/naming.yml', 'summary: s\nitems: []\n');
    await put('context/modules/ops.yml', 'provides: {}\n');
    await put('docs/entities/srv.yml', 'id: srv\nnamespace: vpn\nsummary: сервер\n');
    await put('docs/behavior/handshake.yml', 'id: handshake\nnamespace: vpn\ntitle: t\n');
    await put('docs/manuals/first-run.md', '# Первый запуск\n');
    await put('docs/knowledge/tooling.md', '# Тулинг\n');
    await put('goals/demo.expect.ts', "describe('goal: demo', () => {});\n");
    await put('.ops/demo/research/find.md', 'находка\n');
    await put('.ops/demo/reports/executor-1.md', 'отчёт\n');
    await put('.ops/demo/verdicts/1.yml', 'run: 1\n');
    await put('.ops/demo/baseline/goals/demo.expect.ts', 'baseline\n');
    await put('.ops/feedback/t-1.yml', 'ticket: t\n');

    const lines = await migrateLayout(root);

    expect(lines.join('\n')).not.toContain('legacy');
    expect(await read('.oc3/project.yml')).toBe(project);
    expect(await read('.oc3/conventions/naming.yml')).toBe(convention);
    expect(await read('.oc3/.delta/naming.yml')).toContain('summary: s');
    expect(await read('.oc3/modules/ops.yml')).toContain('provides');
    expect(await read('.oc3/data/entities/srv.yml')).toContain('namespace: vpn');
    expect(await read('.oc3/data/behavior/handshake.yml')).toContain('title: t');
    expect(await read('.oc3/manuals/first-run.md')).toContain('Первый запуск');
    expect(await read('.oc3/knowledge/tooling.md')).toContain('Тулинг');
    expect(existsSync(path.join(root, '.oc3/index.yml'))).toBe(false);
    expect(lines.join('\n')).toContain('index.yml упразднён');
    expect(await read('.oc3/autonomy.yml')).toContain('never');
    expect(await read('.oc3/goals/demo.expect.ts')).toContain('goal: demo');
    expect(await read('.oc3/reports/artifact-history/ops/demo/research/find.md')).toContain(
      'находка',
    );
    expect(await read('.oc3/reports/artifact-history/ops/demo/reports/executor-1.md')).toContain(
      'отчёт',
    );
    expect(await read('.oc3/reports/artifact-history/ops/demo/verdicts/1.yml')).toContain('run: 1');
    expect(
      await read('.oc3/reports/artifact-history/ops/demo/baseline/goals/demo.expect.ts'),
    ).toContain('baseline');
    expect(await read('.oc3/feedback/t-1.yml')).toContain('ticket: t');
    expect(existsSync(path.join(root, 'context'))).toBe(false);
    expect(existsSync(path.join(root, 'docs'))).toBe(false);
    expect(existsSync(path.join(root, 'goals'))).toBe(false);
    expect(existsSync(path.join(root, '.ops'))).toBe(false);
    expect(existsSync(path.join(root, '.oc3/bundles'))).toBe(true);
  });

  it('v3 → v4: переносит .oc3/doc/* в .oc3/*, удаляет index.yml и doc/', async () => {
    const convention = 'key: naming\nsummary: kebab-case\nrule: x\n';
    await put('.oc3/doc/project.yml', 'name: demo\n');
    await put('.oc3/doc/autonomy.yml', 'levels:\n  never: [vcs.write]\n');
    await put('.oc3/doc/conventions/naming.yml', convention);
    await put('.oc3/doc/glossary/common.yml', '- term: api\n');
    await put('.oc3/doc/knowledge/tooling.md', '# Тулинг\n');
    await put('.oc3/doc/data/entities/srv.yml', 'id: srv\nnamespace: vpn\nsummary: сервер\n');
    await put('.oc3/doc/data/__schemas/entities.schema.json', '{"type":"object"}');
    await put('.oc3/doc/index.yml', '# generated by ai context index\n');
    await put('.oc3/doc/manuals/first-run.md', '# Первый запуск\n');

    const lines = await migrateLayout(root);

    expect(await read('.oc3/project.yml')).toBe('name: demo\n');
    expect(await read('.oc3/autonomy.yml')).toContain('never');
    expect(await read('.oc3/conventions/naming.yml')).toBe(convention);
    expect(await read('.oc3/glossary/common.yml')).toContain('api');
    expect(await read('.oc3/knowledge/tooling.md')).toContain('Тулинг');
    expect(await read('.oc3/data/entities/srv.yml')).toContain('namespace: vpn');
    expect(await read('.oc3/data/__schemas/entities.schema.json')).toContain('object');
    expect(await read('.oc3/manuals/first-run.md')).toContain('Первый запуск');
    expect(existsSync(path.join(root, '.oc3/index.yml'))).toBe(false);
    expect(existsSync(path.join(root, '.oc3/doc'))).toBe(false);
    const text = lines.join('\n');
    expect(text).toContain('.oc3/doc/conventions → .oc3/conventions');
    expect(text).toContain('index.yml упразднён');
    expect(text).toContain('.oc3/doc → удалён');
    expect(text).not.toContain('legacy');
  });

  it('v3 → v4: занятая цель не перетирается, doc/ остаётся с legacy-заметкой', async () => {
    await put('.oc3/doc/conventions/naming.yml', 'key: новый\n');
    await put('.oc3/conventions/naming.yml', 'key: прежний\n');

    const lines = await migrateLayout(root);

    expect(lines.join('\n')).toContain('цель уже существует');
    expect(await read('.oc3/conventions/naming.yml')).toBe('key: прежний\n');
    expect(await read('.oc3/doc/conventions/naming.yml')).toBe('key: новый\n');
    expect(existsSync(path.join(root, '.oc3/doc'))).toBe(true);
  });

  it('правит префиксы путей в .oc3/ai-core.yml и .oc3/skills.yml и переписывает .gitignore', async () => {
    await put('context/ai-core.yml', 'rules:\n  - путь: context/conventions/\n');
    await put('context/skills.yml', 'rules:\n  - context/project.yml\n');
    await put('.gitignore', '.ops/operator/\n.ops/locks/\nсвоё\n');

    const lines = await migrateLayout(root);

    expect((await read('.oc3/ai-core.yml')).replace(/\s+/g, ' ')).toContain(
      'путь: .oc3/conventions/',
    );
    expect(await read('.oc3/skills.yml')).toContain('.oc3/project.yml');
    const gitignore = await read('.gitignore');
    expect(gitignore).toContain('.oc3/operator/');
    expect(gitignore).toContain('.oc3/locks/');
    expect(gitignore).toContain('.oc3/bundles/');
    expect(gitignore).not.toContain('.ops/');
    expect(lines.join('\n')).toContain('.gitignore');
  });

  it('v3 → v4: в ai-core.yml заменяет префиксы .oc3/doc/ и ключ context-index → context', async () => {
    await put(
      '.oc3/ai-core.yml',
      'checks:\n  context-index: {}\nrules:\n  - слой: .oc3/doc/conventions/\n',
    );

    const lines = await migrateLayout(root);

    const config = await read('.oc3/ai-core.yml');
    expect(config).toContain('  context: {}\n');
    expect(config).toContain('слой: .oc3/conventions/');
    expect(config).not.toContain('context-index');
    expect(config).not.toContain('.oc3/doc/');
    expect(lines.join('\n')).toContain('ai-core.yml');
  });

  it('не на карте — legacy-хвосты в отчёт без переноса', async () => {
    await put('context/project.yml', 'name: demo\n');
    await put('context/unknown.md', 'хвост\n');
    await put('docs/random.md', 'заметка\n');
    await put('.ops/legacy/other.md', 'файл\n');

    const lines = await migrateLayout(root);

    const text = lines.join('\n');
    expect(text).toContain('legacy — context/unknown.md');
    expect(text).toContain('legacy — docs/random.md');
    expect(text).toContain('artifact-history/manifest.json');
    expect(await read('context/unknown.md')).toBe('хвост\n');
    expect(await read('docs/random.md')).toBe('заметка\n');
    expect(await read('.oc3/reports/artifact-history/ops/legacy/other.md')).toBe('файл\n');
    expect(await read('.oc3/project.yml')).toBe('name: demo\n');
  });

  it('занятая цель не перетирается и уходит в legacy', async () => {
    await put('context/project.yml', 'name: новый\n');
    await put('.oc3/project.yml', 'name: прежний\n');

    const lines = await migrateLayout(root);

    expect(lines.join('\n')).toContain('цель уже существует');
    expect(await read('.oc3/project.yml')).toBe('name: прежний\n');
    expect(await read('context/project.yml')).toBe('name: новый\n');
  });

  it('повторный запуск на новой раскладке — пустой отчёт без действий', async () => {
    await put('context/project.yml', 'name: demo\n');
    await migrateLayout(root);
    const before = await readdir(path.join(root, '.oc3'));
    const lines = await migrateLayout(root);
    expect(lines.join('\n')).not.toContain('layout: .');
    expect((await readdir(path.join(root, '.oc3'))).sort()).toEqual(before.sort());
  });

  it('после переноса создаёт скелет памяти: манифест с перенесёнными файлами и NOTES.md', async () => {
    await put('context/project.yml', 'name: demo\n');
    await put('context/autonomy.yml', 'levels:\n  never: [vcs.write]\n');
    await put(
      'context/conventions/naming.yml',
      '- key: kebab\n  summary: имена\n  rule: kebab-case\n',
    );
    await put('docs/entities/srv.yml', 'id: srv\nnamespace: vpn\nsummary: сервер\n');
    await put('docs/manuals/first-run.md', '# Первый запуск\n');

    const lines = await migrateLayout(root);

    const manifest: unknown = JSON.parse(
      await readFile(path.join(root, '.oc3/manifest.json'), 'utf8'),
    );
    expect(manifest).toMatchObject({
      namespace: [],
      data: ['entities'],
      budgets: { notes: 4096, start: 24576, node: 16384, optional_field: 3 },
    });
    const files = isRecord(manifest) && isRecord(manifest['files']) ? manifest['files'] : {};
    expect(files['project.yml']).toBeUndefined();
    expect(files['autonomy.yml']).toBeUndefined();
    expect(files['conventions/naming.yml']).toEqual({ namespace: [], weight: 2 });
    expect(files['data/entities/srv.yml']).toEqual({ namespace: [], weight: 2 });
    expect(files['manuals/first-run.md']).toEqual({ namespace: [], weight: 2 });
    expect(await readFile(path.join(root, '.oc3/NOTES.md'), 'utf8')).toContain(
      '# NOTES — неформальные факты до формализации',
    );
    expect(lines.join('\n')).toContain('скелет');
  });

  it('повторная миграция сохраняет пользовательские веса манифеста', async () => {
    await put('context/project.yml', 'name: demo\n');
    await put(
      'context/conventions/naming.yml',
      '- key: kebab\n  summary: имена\n  rule: kebab-case\n',
    );
    await migrateLayout(root);
    const manifest: unknown = JSON.parse(
      await readFile(path.join(root, '.oc3/manifest.json'), 'utf8'),
    );
    const files = isRecord(manifest) && isRecord(manifest['files']) ? manifest['files'] : {};
    files['conventions/naming.yml'] = { namespace: ['docs'], weight: 7 };
    await writeFile(
      path.join(root, '.oc3/manifest.json'),
      `${JSON.stringify(manifest, null, 2)}\n`,
      'utf8',
    );

    await migrateLayout(root);

    const next: unknown = JSON.parse(await readFile(path.join(root, '.oc3/manifest.json'), 'utf8'));
    const nextFiles = isRecord(next) && isRecord(next['files']) ? next['files'] : {};
    expect(nextFiles['conventions/naming.yml']).toEqual({ namespace: ['docs'], weight: 7 });
  });
});
