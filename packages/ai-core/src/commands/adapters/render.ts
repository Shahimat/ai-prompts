import type { AgentDef } from './source.ts';

export const GENERATED_MARK = 'generated by ai adapters sync';

const tomlString = (value: string): string => JSON.stringify(value);

function tomlMultiline(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/"""/g, '""\\"')
    .replace(/[^]/g, (c) => {
      const code = c.charCodeAt(0);
      const control = (code < 0x20 && code !== 0x09 && code !== 0x0a) || code === 0x7f;
      return control ? `\\u${code.toString(16).padStart(4, '0')}` : c;
    });
  return `"""\n${escaped}\n"""`;
}

export function codexAgent(agent: AgentDef): string {
  const preface =
    agent.skills.length > 0 ? `Перед работой загрузи skills: ${agent.skills.join(', ')}.\n\n` : '';
  return [
    `# ${GENERATED_MARK} from ${agent.source} — do not edit`,
    `name = ${tomlString(agent.name)}`,
    `description = ${tomlString(agent.description)}`,
    `developer_instructions = ${tomlMultiline(preface + agent.instructions)}`,
    '',
  ].join('\n');
}
