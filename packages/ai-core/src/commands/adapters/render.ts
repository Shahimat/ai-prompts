// expect:claude-md-import
import { stringify } from 'yaml';
import type { AgentDef } from './source.ts';

export const GENERATED_MARK = 'generated by ai-core adapters sync';

export const SKILL_MARKER_FILE = '.harness-generated';

export function claudeMd(): string {
  return `<!-- ${GENERATED_MARK} — do not edit, правь AGENTS.md -->\n@AGENTS.md\n`;
}

export function skillMarker(name: string): string {
  return `${GENERATED_MARK} from .agents/skills/${name} — do not edit\n`;
}

export function claudeAgent(agent: AgentDef): string {
  const fields: Record<string, unknown> = { name: agent.name, description: agent.description };
  if (agent.tools.length > 0) fields['tools'] = agent.tools.join(', ');
  if (agent.skills.length > 0) fields['skills'] = agent.skills;
  if (agent.model !== undefined) fields['model'] = agent.model;
  const yaml = stringify(fields, { lineWidth: 0 });
  return `---\n# ${GENERATED_MARK} from ${agent.source} — do not edit\n${yaml}---\n\n${agent.instructions}\n`;
}

const tomlString = (value: string): string => JSON.stringify(value);

function tomlMultiline(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/"""/g, '""\\"')
    .replace(/[^]/g, (c) => {
      const code = c.charCodeAt(0);
      const control = (code < 0x20 && code !== 0x09 && code !== 0x0a) || code === 0x7f;
      return control ? `\\u${code.toString(16).padStart(4, '0')}` : c;
    });
  return `"""\n${escaped}\n"""`;
}

export function codexAgent(agent: AgentDef): string {
  const preface =
    agent.skills.length > 0 ? `Перед работой загрузи skills: ${agent.skills.join(', ')}.\n\n` : '';
  return [
    `# ${GENERATED_MARK} from ${agent.source} — do not edit`,
    `name = ${tomlString(agent.name)}`,
    `description = ${tomlString(agent.description)}`,
    `developer_instructions = ${tomlMultiline(preface + agent.instructions)}`,
    '',
  ].join('\n');
}
