import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import { buildContextIndex, checkContextIndex } from '#commands/context/context-index';
import { CONTEXT_INDEX_PATH } from '#shared/layout';
import { isRecord } from '#shared/guards';

let root: string;

function namespacesOf(text: string): Record<string, unknown> {
  const index: unknown = parse(text);
  if (!isRecord(index) || !isRecord(index['namespaces'])) throw new Error('нет namespaces');
  return index['namespaces'];
}

async function put(rel: string, content: string): Promise<void> {
  await mkdir(path.dirname(path.join(root, rel)), { recursive: true });
  await writeFile(path.join(root, rel), content, 'utf8');
}

async function messages(): Promise<string[]> {
  const { diagnostics } = await buildContextIndex(root);
  return diagnostics.map((d) => `${d.file}: ${d.message}`);
}

async function seed(): Promise<void> {
  await put(
    'context/project.yml',
    'name: demo\nnamespaces:\n  vpn: удалённый доступ\n  infra: инфраструктура\n',
  );
  await put(
    'docs/entities/vpn-server.yml',
    'id: vpn-server\nkind: entity\nnamespace: vpn\nsummary: "сервер: AWG на 51820"\nmanuals: [first-run]\n',
  );
  await put(
    'docs/entities/ansible-layout.yml',
    'id: ansible-layout\nnamespace: infra\nsummary: раскладка\nmanuals: [docs/manuals/first-run.md]\n',
  );
  await put(
    'docs/behavior/handshake-ok.yml',
    'id: handshake-ok\nnamespace: vpn\ntitle: handshake работает\n',
  );
  await put(
    'context/conventions/naming.yml',
    'key: naming\nsummary: kebab-case\nrule: |\n  длинный текст\n',
  );
  await put(
    'context/conventions/code/strict-ts.yml',
    'key: strict-ts\nsummary: strict везде\nrule: x\n',
  );
  await put('docs/manuals/first-run.md', '# Первый запуск\n\n## Шаги\n');
}

beforeEach(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'harness-ctx-'));
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

describe('buildContextIndex', () => {
  it('собирает индекс из слоёв', async () => {
    await seed();
    const { text, diagnostics } = await buildContextIndex(root);
    expect(diagnostics).toEqual([]);
    expect(text.split('\n')[0]).toBe('# generated by ai-core context index — do not edit manually');
    expect(parse(text)).toEqual({
      conventions: { naming: 'kebab-case', 'strict-ts': 'strict везде' },
      namespaces: {
        vpn: {
          description: 'удалённый доступ',
          entities: { 'vpn-server': 'сервер: AWG на 51820' },
          behaviors: { 'handshake-ok': 'handshake работает' },
          manuals: { 'first-run': 'Первый запуск' },
        },
        infra: {
          description: 'инфраструктура',
          entities: { 'ansible-layout': 'раскладка' },
          manuals: { 'first-run': 'Первый запуск' },
        },
      },
    });
  });

  it('детерминирован: namespace в порядке project.yml, id по алфавиту, без даты', async () => {
    await seed();
    await put('docs/entities/a-first.yml', 'id: a-first\nnamespace: vpn\nsummary: a\n');
    const { text } = await buildContextIndex(root);
    expect(text).not.toMatch(/generated_at/);
    expect(text.indexOf('  vpn:')).toBeLessThan(text.indexOf('  infra:'));
    expect(text.indexOf('a-first')).toBeLessThan(text.indexOf('vpn-server'));
    expect((await buildContextIndex(root)).text).toBe(text);
  });

  it('пустой проект — только заголовок и пустой документ, нарушение про project.yml', async () => {
    const { text, diagnostics } = await buildContextIndex(root);
    expect(text.startsWith('# generated by ai-core context index')).toBe(true);
    expect(diagnostics.map((d) => d.file)).toEqual(['context/project.yml']);
  });

  it('нарушения: id, namespace, summary, title, H1, manual без ссылок', async () => {
    await seed();
    await put('docs/entities/wrong-name.yml', 'id: other\nnamespace: vpn\nsummary: x\n');
    await put('docs/entities/no-ns.yml', 'id: no-ns\nsummary: x\n');
    await put('docs/entities/alien.yml', 'id: alien\nnamespace: misc\nsummary: x\n');
    await put('docs/entities/no-summary.yml', 'id: no-summary\nnamespace: vpn\n');
    await put(
      'docs/entities/multi.yml',
      'id: multi\nnamespace: vpn\nsummary: |\n  строка 1\n  строка 2\n',
    );
    await put('docs/behavior/no-title.yml', 'id: no-title\nnamespace: vpn\n');
    await put('docs/manuals/orphan.md', '# Сирота\n');
    await put('docs/manuals/no-h1.md', 'текст\n');
    await put(
      'docs/entities/refs-no-h1.yml',
      'id: refs-no-h1\nnamespace: vpn\nsummary: x\nmanuals: [no-h1]\n',
    );
    await put('context/conventions/dup.yml', 'key: naming\nsummary: x\n');
    await put('docs/entities/broken.yml', 'id: [\n');

    expect(await messages()).toEqual([
      'docs/entities/alien.yml: namespace «misc» не объявлен в context/project.yml → namespaces',
      expect.stringMatching(/^docs\/entities\/broken\.yml: невалидный YAML: /),
      'docs/entities/multi.yml: summary должно быть одной строкой',
      'docs/entities/no-ns.yml: нет поля namespace',
      'docs/entities/no-summary.yml: нет поля summary (одна строка для индекса)',
      'docs/entities/wrong-name.yml: id «other» не совпадает с именем файла «wrong-name»',
      'docs/behavior/no-title.yml: нет поля title (одна строка для индекса)',
      'context/conventions/dup.yml: key «naming» не совпадает с именем файла «dup»',
      'context/conventions/naming.yml: key «naming» уже занят другой convention',
      'docs/manuals/no-h1.md: нет заголовка «# …» (одна строка для индекса)',
      'docs/manuals/orphan.md: manual не упомянут ни в одной entity (поле manuals) — namespace не определить',
    ]);
  });

  it('необъявленный namespace всё равно попадает в индекс, после объявленных', async () => {
    await seed();
    await put('docs/entities/alien.yml', 'id: alien\nnamespace: misc\nsummary: x\n');
    const namespaces = namespacesOf((await buildContextIndex(root)).text);
    expect(Object.keys(namespaces)).toEqual(['vpn', 'infra', 'misc']);
  });
});

describe('checkContextIndex', () => {
  it('нет индекса', async () => {
    await seed();
    expect((await checkContextIndex(root)).map((d) => d.message)).toEqual([
      'файл не найден: запусти ai-core context index',
    ]);
  });

  it('актуальный индекс, в том числе с CRLF', async () => {
    await seed();
    const { text } = await buildContextIndex(root);
    await put(CONTEXT_INDEX_PATH, text.replace(/\n/g, '\r\n'));
    expect(await checkContextIndex(root)).toEqual([]);
  });

  it('устаревший индекс', async () => {
    await seed();
    await put(CONTEXT_INDEX_PATH, (await buildContextIndex(root)).text);
    await put('docs/entities/new.yml', 'id: new\nnamespace: vpn\nsummary: x\n');
    expect((await checkContextIndex(root)).map((d) => d.message)).toEqual([
      'устарел: запусти ai-core context index',
    ]);
  });
});

describe('слои модулей (provides.index_layers)', () => {
  const MANIFEST =
    'key: knowledge-external-gui\nprovides:\n  index_layers:\n    - section: knowledge\n      dir: docs/knowledge/\n';
  const card = (id: string, ns = 'vpn', title = '# Provider: вебхуки'): string =>
    `---\n# комментарий YAML не заголовок\nid: ${id}\nkind: knowledge\nnamespace: ${ns}\n---\n\n${title}\n\n## Карта\n`;

  it('индексирует слой модуля по namespace', async () => {
    await seed();
    await put('context/modules/knowledge-external-gui.yml', MANIFEST);
    await put('docs/knowledge/provider/webhooks.md', card('provider-webhooks'));
    await put('docs/knowledge/other/login.md', card('other-login', 'infra', '# Other: вход'));
    const { text, diagnostics } = await buildContextIndex(root);
    expect(diagnostics).toEqual([]);
    const namespaces = namespacesOf(text);
    expect(namespaces).toHaveProperty(['vpn', 'knowledge'], {
      'provider-webhooks': 'Provider: вебхуки',
    });
    expect(namespaces).toHaveProperty(['infra', 'knowledge'], { 'other-login': 'Other: вход' });
    const vpn = namespaces['vpn'];
    expect(Object.keys(isRecord(vpn) ? vpn : {})).toEqual([
      'description',
      'entities',
      'behaviors',
      'manuals',
      'knowledge',
    ]);
  });

  it('модуль без index_layers и слой без файлов — ничего не добавляют', async () => {
    await seed();
    await put(
      'context/modules/code-rules.yml',
      'key: code-rules\nprovides:\n  layers: [context/conventions/code/]\n',
    );
    await put('context/modules/knowledge-external-gui.yml', MANIFEST);
    const before = await buildContextIndex(root);
    expect(before.diagnostics).toEqual([]);
    expect(before.text).not.toMatch(/knowledge/);
  });

  it('нарушения в манифесте и файлах слоя', async () => {
    await seed();
    await put('context/modules/a.yml', MANIFEST);
    await put(
      'context/modules/b.yml',
      'provides:\n  index_layers:\n    - section: knowledge\n      dir: docs/k2\n    - section: entities\n      dir: x\n    - section: ok\n      dir: ../outside\n',
    );
    await put('context/modules/c.yml', 'provides:\n  index_layers: knowledge\n');
    await put('docs/knowledge/p/wrong.md', card('other-id'));
    await put('docs/knowledge/p/no-fm.md', '# Без frontmatter\n');
    await put('docs/knowledge/p/no-h1.md', '---\nid: p-no-h1\nnamespace: vpn\n---\nтекст\n');
    await put('docs/knowledge/p/alien.md', card('p-alien', 'misc'));
    await put('docs/knowledge/p/no-id.md', '---\nnamespace: vpn\n---\n# x\n');
    expect(await messages()).toEqual([
      'context/modules/b.yml: index_layers: section «knowledge» уже объявлена в context/modules/a.yml',
      'context/modules/b.yml: index_layers: section «entities» — нужен kebab-case, не description/entities/behaviors/manuals',
      'context/modules/b.yml: index_layers: dir «../outside» — нужен путь внутри проекта',
      'context/modules/c.yml: provides.index_layers должно быть списком',
      'docs/knowledge/p/alien.md: namespace «misc» не объявлен в context/project.yml → namespaces',
      'docs/knowledge/p/no-fm.md: нет frontmatter (id, namespace)',
      'docs/knowledge/p/no-h1.md: нет заголовка «# …» (одна строка для индекса)',
      'docs/knowledge/p/no-id.md: нет поля id',
      'docs/knowledge/p/wrong.md: id «other-id» не совпадает с путём «p-wrong»',
    ]);
  });
});

describe('слои модулей в формате yml', () => {
  const MANIFEST =
    'provides:\n  index_layers:\n    - section: facts\n      dir: life/facts\n      format: yml\n';

  it('индексирует yml по summary', async () => {
    await seed();
    await put('context/modules/life.yml', MANIFEST);
    await put(
      'life/facts/sleep/baseline.yml',
      'id: sleep-baseline\nnamespace: vpn\nsummary: сон — базовая линия\n',
    );
    const { text, diagnostics } = await buildContextIndex(root);
    expect(diagnostics).toEqual([]);
    expect(namespacesOf(text)).toHaveProperty(['vpn', 'facts'], {
      'sleep-baseline': 'сон — базовая линия',
    });
  });

  it('нарушения: нет summary, id не по пути, неизвестный format', async () => {
    await seed();
    await put('context/modules/life.yml', MANIFEST);
    await put(
      'context/modules/bad.yml',
      'provides:\n  index_layers:\n    - section: x\n      dir: x\n      format: json\n',
    );
    await put('life/facts/a.yml', 'id: b\nnamespace: vpn\n');
    expect(await messages()).toEqual([
      'context/modules/bad.yml: index_layers: format «json» — md или yml',
      'life/facts/a.yml: нет поля summary (одна строка для индекса)',
      'life/facts/a.yml: id «b» не совпадает с путём «a»',
    ]);
  });
});
